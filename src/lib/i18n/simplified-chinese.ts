function simplify(value: unknown): unknown {
  if (typeof value === "string") {
    // 1. First replace domain-specific terms (preserving context)
    let result = value;
    for (const [traditionalTerm, simplifiedTerm] of terminologyMap) {
      result = result.replaceAll(traditionalTerm, simplifiedTerm);
    }
    // 2. Character-by-character traditional to simplified conversion
    result = result.replace(/[\s\S]/g, (character) => characterMap.get(character) ?? character);
    return result;
  }
  if (Array.isArray(value)) return value.map(simplify);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, simplify(entry)]));
  }
  return value;
}

export function toSimplifiedChinese<T>(value: T): T {
  return simplify(value) as T;
}

export function withSimplifiedChinese<T extends { "zh-hant": unknown }>(
  translations: T & { "zh-hans"?: T["zh-hant"] }
): T & { "zh-hans": T["zh-hant"] } {
  return {
    ...translations,
    "zh-hans": (translations["zh-hans"] as T["zh-hant"]) ?? toSimplifiedChinese(translations["zh-hant"]),
  };
}

export function getLocalizedValue<T>(translations: { "zh-hant": T } & Partial<Record<Locale, T>>, locale: Locale): T {
  const value = translations[locale] ?? translations["zh-hant"];
  return locale === "zh-hans" ? toSimplifiedChinese(value) : value;
}
